type Mini = {
  id: string;
  mg: string;
  fr?: string;
  en?: string;
  incertain?: boolean;
  desc: string;
  accroche: string;
  cats: string[];
  regions?: string[];
  ings: string[];
  type: TypePlat;
  mode?: Plat['modePreparation'];
  arch: ArchetypeVisuel;
  pal: keyof typeof palettes;
  prix: number;
  unite: Unite;
  q?: number;
  prep?: number;
  cuis?: number;
  diff?: Plat['difficulte'];
  chaud: boolean;
  alcool?: boolean;
  nutri?: Plat['nutrition'];
  pop: number;
  note?: number;
  tags: string[];
  vedette?: boolean;
  nouveau?: boolean;
  hist?: string;
};

const plat = (m: Mini): Plat => ({
  id: `plat-${m.id}`,
  slug: m.id,
  photo: photosPlats[m.id],
  nom: { malagasy: m.mg, francais: m.fr, anglais: m.en },
  nomMalagasyIncertain: m.incertain,
  aRelire: true,
  description: m.desc,
  phraseAccroche: m.accroche,
  histoire: m.hist,
  categorieIds: m.cats.map((c) => `cat-${c}`),
  regionIds: (m.regions ?? []).map((r) => `reg-${r}`),
  ingredientIds: m.ings,
  typePlat: m.type,
  modePreparation: m.mode,
  archetype: m.arch,
  palette: palettes[m.pal] ?? {
    assiette: '#F4E9E8',
    base: '#5B3441',
    accent1: '#9B536C',
    accent2: '#C78492',
    ombre: '#35232B',
  },
  galerie: [`gal-${m.id}-1`, `gal-${m.id}-2`].slice(0, 2),
  tempsPreparation: m.prep,
  tempsCuisson: m.cuis,
  difficulte: m.diff,
  chaud: m.chaud,
  contientAlcool: m.alcool,
  nutrition: m.nutri,
  prixIndicatif: {
    valeur: m.prix,
    devise: 'MGA',
    unite: m.unite,
    quantitePortion: m.q ?? 1,
    estFictif: true,
  },
  popularite: m.pop,
  note: m.note,
  noteEstFictive: true,
  tags: m.tags,
  estVedette: Boolean(m.vedette),
  estNouveau: m.nouveau,
  statutDonnees: 'demonstration',
});

const n = (calories: number, proteines: number, glucides: number, lipides: number): Plat['nutrition'] => ({
  calories,
  proteines,
  glucides,
  lipides,
  source: 'Valeurs indicatives et fictives',
  estIndicatif: true,
});

